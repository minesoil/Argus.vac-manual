#!/usr/bin/env python3
"""
cv-environment-diagnostic.py
Argus Vac - Computer Vision Environment Analyzer (v1.1)
Developed for Orange Pi 5

This script captures 100 frames from the USB camera and reports your room's
lighting stability, floor color statistics, and sensor noise levels. Run it once
per new environment and paste the console output into an AI chat - it tells the
assistant exactly what thresholds make sense.

Since detector build 10.x this also serves as a pre-flight check for the
unknown-obstacle layer: dim, flickering, or extremely busy floors are exactly
the conditions that need ANOMALY_SENSITIVITY tuning.
"""

import cv2
import numpy as np
import sys
import time

def main():
    print("=====================================================================")
    print("      ARGUS VAC - CV ENVIRONMENT ANALYZER (v1.1)                  ")
    print("=====================================================================")
    print("Scanning camera hardware... Please ensure camera is pointed at your floor.")
    
    # Initialize camera
    cap = cv2.VideoCapture(0)
    if not cap.isOpened():
        print("\n[FATAL ERROR] Could not open USB camera (index 0).")
        print("Please check connection or run 'ls /dev/video*'.")
        sys.exit(1)
        
    # Allow camera auto-exposure and white balance to settle (critical for realistic readings)
    print("Stabilizing camera auto-exposure (2 seconds)...")
    time.sleep(2.0)
    
    # Force standard resolution
    cap.set(cv2.CAP_PROP_FRAME_WIDTH, 640)
    cap.set(cv2.CAP_PROP_FRAME_HEIGHT, 480)
    
    # Driving corridor ROI: bottom-middle of the frame, where floor obstacles appear first
    roi_top_pct = 0.55
    roi_left_pct = 0.3
    roi_right_pct = 0.7
    
    # Diagnostic collections
    frame_brightness_means = []
    hsv_h_values = []
    hsv_s_values = []
    hsv_v_values = []
    
    canny_edge_counts_low_thresh = []
    canny_edge_counts_high_thresh = []
    
    frame_count = 100
    print(f"Collecting statistical telemetry over {frame_count} frames...")
    
    for i in range(frame_count):
        ret, frame = cap.read()
        if not ret:
            time.sleep(0.01)
            continue
            
        height, width, _ = frame.shape
        roi_y_start = int(height * roi_top_pct)
        roi_y_end = height
        roi_x_start = int(width * roi_left_pct)
        roi_x_end = int(width * roi_right_pct)
        
        # Crop to corridor
        roi = frame[roi_y_start:roi_y_end, roi_x_start:roi_x_end]
        
        # 1. Grayscale Analysis
        gray = cv2.cvtColor(roi, cv2.COLOR_BGR2GRAY)
        frame_brightness_means.append(np.mean(gray))
        
        # 2. HSV Channel Analysis
        hsv = cv2.cvtColor(roi, cv2.COLOR_BGR2HSV)
        h, s, v = cv2.split(hsv)
        hsv_h_values.append(np.mean(h))
        hsv_s_values.append(np.mean(s))
        hsv_v_values.append(np.mean(v))
        
        # 3. Canny Edge Density Analysis
        # Test low-sensitivity Canny (50, 150)
        edges_low = cv2.Canny(gray, 50, 150)
        canny_edge_counts_low_thresh.append(np.sum(edges_low > 0))
        
        # Test high-sensitivity Canny (100, 200)
        edges_high = cv2.Canny(gray, 100, 200)
        canny_edge_counts_high_thresh.append(np.sum(edges_high > 0))
        
        if i % 20 == 0:
            print(f"  [Progress] Analyzed {i}/{frame_count} frames...")
            
    cap.release()
    print("\nProcessing telemetry metrics... Formatting Claude Diagnostic Report...")
    print("=====================================================================\n")
    
    # Calculate statistics
    avg_brightness = np.mean(frame_brightness_means)
    std_brightness = np.std(frame_brightness_means)  # Measures flicker / lighting stability
    min_brightness = np.min(frame_brightness_means)
    max_brightness = np.max(frame_brightness_means)
    
    avg_h = np.mean(hsv_h_values)
    avg_s = np.mean(hsv_s_values)
    avg_v = np.mean(hsv_v_values)
    
    # Noise and edge densities (percentage of pixels that registered as edge noise on clean floor)
    total_roi_pixels = (640 * (1.0 - roi_top_pct)) * (640 * (roi_right_pct - roi_left_pct))
    avg_edges_low = np.mean(canny_edge_counts_low_thresh)
    avg_edges_high = np.mean(canny_edge_counts_high_thresh)
    
    edge_density_low = (avg_edges_low / total_roi_pixels) * 100
    edge_density_high = (avg_edges_high / total_roi_pixels) * 100

    # Output highly structured Markdown for Claude
    print("### COPY THE BLOCK BELOW AND PASTE IT TO CLAUDE ###")
    print("```markdown")
    print("# ARGUS VAC - HARDWARE & ENVIRONMENTAL DIAGNOSTIC TELEMETRY")
    print("Generated by: cv-environment-diagnostic.py (v1)")
    print("Target Hardware: Orange Pi 5 (8GB) with USB Camera")
    print(f"Sample Size: {frame_count} Frames (Consecutive)")
    print("--------------------------------------------------")
    print("## 1. PHYSICAL LIGHTING & LUMINANCE STATISTICS (Grayscale)")
    print(f"- **Average Floor Luminance (0-255 scale):** {avg_brightness:.2f}")
    print(f"- **Luminance Peak Range:** {min_brightness:.1f} (Min) to {max_brightness:.1f} (Max)")
    print(f"- **Lighting Stability (Standard Deviation):** {std_brightness:.3f} px")
    print("  *Interpretation:* ")
    if std_brightness > 2.0:
        print("  *WARNING: Extreme exposure oscillation or light flickering detected. Auto-exposure on Pi must be manually locked.*")
    elif avg_brightness < 40:
        print("  *WARNING: Ambient lighting is extremely dim. Edge-detection will suffer heavy sensor noise.*")
    elif avg_brightness > 200:
        print("  *WARNING: Over-exposed/extremely bright flooring. Shadows will produce hyper-intense contrast lines.*")
    else:
        print("  *STATUS: Lighting environment is highly stable and within nominal operating levels.*")
        
    print("\n## 2. HSV (COLOR SPACE) DISTRIBUTION")
    print(f"- **Mean Hue (H, 0-179):** {avg_h:.2f}")
    print(f"- **Mean Saturation (S, 0-255):** {avg_s:.2f}")
    print(f"- **Mean Value/Brightness (V, 0-255):** {avg_v:.2f}")
    print("  *Interpretation:*")
    if avg_s < 30:
        print("  *Floor color profile is highly monochromatic (greys/whites/shadows). HSV detection must use high Saturation/Value lower bounds to prevent background noise triggers.*")
    else:
        print("  *Floor contains distinct color temperatures. Narrow-band HSV filtering can safely isolate bright target obstacles.*")
        
    print("\n## 3. FLOOR EDGE & RESOLUTION NOISE STATISTICS")
    print(f"- **Total Driving Corridor ROI Pixels:** {int(total_roi_pixels)} px")
    print(f"- **Canny Edges Detected at (50, 150) threshold:** {avg_edges_low:.1f} average pixels")
    print(f"- **Floor Edge Density (50, 150):** {edge_density_low:.3f}%")
    print(f"- **Canny Edges Detected at (100, 200) threshold:** {avg_edges_high:.1f} average pixels")
    print(f"- **Floor Edge Density (100, 200):** {edge_density_high:.3f}%")
    print("  *Interpretation:*")
    if edge_density_low > 1.5:
        print("  *WARNING: Floor has highly busy texture (wood grain, carpet fibers, tile grout) or high sensor noise. Canny low-limit must be raised (> 100) and bilateral smoothing must be increased.*")
    else:
        print("  *STATUS: Clean/uniform floor surface. Low-contrast edge detection is safe to use.*")
        
    print("\n## 4. DESIGNED HARDWARE PIN MAPPINGS (Reference)")
    print("- **Left Stepper (A4988):** Step Pin 5, Dir Pin 6")
    print("- **Right Stepper (A4988):** Step Pin 3, Dir Pin 4")
    print("- **Dual N20 Sweep Motors (L298N):** Pins 7, 8, 9, 10")
    print("- **San Ace 40 Vacuum Fan (drv-1012):** PWM Pin 11, Dir Pin 12, Brake Pin 2")
    print("- **Master Overrides:** Emergency Halt on ASCII character 'H', Release on ASCII character 'G'")
    print("```")
    print("=====================================================================")

if __name__ == "__main__":
    main()
